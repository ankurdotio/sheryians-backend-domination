import mongoose from "mongoose";

const userSchema = new mongoose.Schema({
    username: {
        type: String,
        required: true,
        unique: true,
        trim: true,
    },
    email: {
        type: String,
        required: true,
        unique: true,
        trim: true,
    },
    password: {
        type: String,
        required: true,
        select: false, // Exclude password from query results by default
    }
}, {
    timestamps: true,
});


const userModel = mongoose.model("users", userSchema);


export default userModel;